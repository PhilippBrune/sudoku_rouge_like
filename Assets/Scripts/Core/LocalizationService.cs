        public static void SetLanguage(LanguageOption lang)
        {
            _current = lang;
        }

        public static LanguageOption Current => _current;

        public static IReadOnlyList<string> RequiredCreditKeys => CreditLocalizationKeys;

        public static IReadOnlyList<string> RequiredRuntimeFeedbackKeys => RuntimeFeedbackLocalizationKeys;

        public static IReadOnlyList<string> MissingGermanKeys => _missingGermanKeys
            .OrderBy(key => key)
            .ToList();

        public static IReadOnlyList<string> ExternalCatalogDiagnostics
        {
            get
            {
                EnsureExternalCatalogsLoaded();
                return _externalCatalogDiagnostics.ToList();
            }
        }

        public static void ResetDiagnostics()
        {
            _missingGermanKeys.Clear();
        }

        public static bool HasGermanTranslation(string key)
        {
            EnsureExternalCatalogsLoaded();
            return !string.IsNullOrEmpty(key) && (ExternalDe.ContainsKey(key) || De.ContainsKey(key));
        }

        public static IReadOnlyList<string> FindMissingGermanTranslations(IEnumerable<string> keys)
        {
            if (keys == null)
                return new List<string>();

            return keys
                .Where(key => !string.IsNullOrEmpty(key) && !HasGermanTranslation(key))
                .Distinct()
                .OrderBy(key => key)
                .ToList();
        }

        public static int GetExternalCatalogEntryCount(LanguageOption language)
        {
            EnsureExternalCatalogsLoaded();
            return language == LanguageOption.German ? ExternalDe.Count : ExternalEn.Count;
        }

        public static bool HasExternalCatalogEntry(LanguageOption language, string key)
        {
            if (string.IsNullOrEmpty(key))
                return false;

            EnsureExternalCatalogsLoaded();
            return language == LanguageOption.German
                ? ExternalDe.ContainsKey(key)
                : ExternalEn.ContainsKey(key);
        }

        public static string T(string key)
        {
            return T(key, key);
        }

        public static string T(string key, string englishFallback)
        {
            if (string.IsNullOrEmpty(key))
                return string.Empty;

            EnsureExternalCatalogsLoaded();

            if (_current == LanguageOption.English)
            {
                if (ExternalEn.TryGetValue(key, out var externalEnglish))
                    return externalEnglish;

                return En.TryGetValue(key, out var en) ? en : englishFallback ?? key;
            }

            if (ExternalDe.TryGetValue(key, out var externalGerman))
                return externalGerman;

            if (De.TryGetValue(key, out var val))
                return val;

            _missingGermanKeys.Add(key);
            if (ExternalEn.TryGetValue(key, out var externalFallback))
                return externalFallback;

            return En.TryGetValue(key, out var fallback) ? fallback : englishFallback ?? key;
        }

        public static string Format(string key, string englishFallback, params object[] args)
        {
            return string.Format(T(key, englishFallback), args);
        }

        public static string Plural(
            int count,
            string singularKey,
            string pluralKey,
            string singularEnglishFallback,
            string pluralEnglishFallback)
        {
            return T(
                count == 1 ? singularKey : pluralKey,
                count == 1 ? singularEnglishFallback : pluralEnglishFallback);
        }

        public static string FormatPlural(
            int count,
            string singularKey,
            string pluralKey,
            string singularEnglishFallback,
            string pluralEnglishFallback,
            params object[] additionalArgs)
        {
            var args = new object[(additionalArgs?.Length ?? 0) + 1];
            args[0] = count;
            if (additionalArgs != null)
                for (var i = 0; i < additionalArgs.Length; i++)
                    args[i + 1] = additionalArgs[i];

            return string.Format(
                Plural(count, singularKey, pluralKey, singularEnglishFallback, pluralEnglishFallback),
                args);
        }

        private static void EnsureExternalCatalogsLoaded()
        {
            if (_externalCatalogsLoaded)
                return;

            _externalCatalogsLoaded = true;
            LoadExternalCatalog(EnglishCatalogResourcePath, ExternalEn, "English");
            LoadExternalCatalog(GermanCatalogResourcePath, ExternalDe, "German");
        }

        private static void LoadExternalCatalog(string resourcePath, Dictionary<string, string> target, string languageName)
        {
            TextAsset asset;
            try
            {
                asset = Resources.Load<TextAsset>(resourcePath);
            }
            catch (System.Exception ex)
            {
                _externalCatalogDiagnostics.Add($"{languageName} catalog load failed: {ex.Message}");
                return;
            }

            if (asset == null)
            {
                _externalCatalogDiagnostics.Add($"{languageName} catalog not found at Resources/{resourcePath}.json; code fallback active.");
                return;
            }

            Dictionary<string, string> parsed;
            try
            {
                parsed = JsonConvert.DeserializeObject<Dictionary<string, string>>(asset.text);
            }
            catch (System.Exception ex)
            {
                _externalCatalogDiagnostics.Add($"{languageName} catalog parse failed: {ex.Message}");
                return;
            }

            if (parsed == null)
            {
                _externalCatalogDiagnostics.Add($"{languageName} catalog parsed as empty; code fallback active.");
                return;
            }

            foreach (var entry in parsed)
            {
                if (string.IsNullOrEmpty(entry.Key) || entry.Value == null)
                    continue;

                target[entry.Key] = entry.Value;
            }
        }
